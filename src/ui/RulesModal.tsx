import { useState } from 'react';

interface Props {
  onClose(): void;
}

export default function RulesModal({ onClose }: Props) {
  const [tab, setTab] = useState<'long' | 'short'>('long');

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal modal-wide" onClick={(e) => e.stopPropagation()}>
        <h2>Как играть</h2>
        <div className="seg seg-center">
          <button className={tab === 'long' ? 'seg-on' : ''} onClick={() => setTab('long')}>Длинные нарды</button>
          <button className={tab === 'short' ? 'seg-on' : ''} onClick={() => setTab('short')}>Короткие нарды</button>
        </div>

        {tab === 'long' ? (
          <div className="rules-body">
            <p>Главный режим КотоИмперии. Цель — провести все 15 лапок по кругу в свой дом и сбросить их с доски первым.</p>
            <ul>
              <li>Все 15 фишек начинают на «голове» — стартовом пункте на противоположной стороне.</li>
              <li>Фишки соперника не сбиваются. Пункт с хотя бы одной чужой фишкой <b>закрыт</b>.</li>
              <li>На своём пункте может стоять любое количество своих фишек.</li>
              <li>С головы обычно снимается <b>одна</b> фишка за ход. Спортивное правило: второй игрок на первом броске при дубле 3–3, 4–4 или 6–6 может снять две.</li>
              <li>Допустим непрерывный <b>блок из шести</b> занятых пунктов — но нельзя запирать им все 15 фишек соперника.</li>
              <li>Когда все 15 фишек вошли в дом, начинается выбрасывание: нужно точное значение кости, лишнее — по правилу старшей фишки.</li>
              <li>Не забудьте: обе кости должны быть сыграны, если возможно. Дубль — четыре хода.</li>
            </ul>
          </div>
        ) : (
          <div className="rules-body">
            <p>Классический backgammon. Игроки движутся в противоположных направлениях, сбивают блоты и гонят фишки в свой дом.</p>
            <ul>
              <li>Начальная расстановка: <b>2–5–3–5</b> (пункты 24, 13, 8, 6).</li>
              <li>Пункт с двумя и более фишками соперника <b>закрыт</b>.</li>
              <li>Одиночная фишка — <b>блот</b>: приходящая фишка сбивает её на <b>бар</b>.</li>
              <li>Пока на баре есть фишки, ходить можно только ими — возврат в игр обязателен.</li>
              <li>Возврат происходит в дом соперника: открытый пункт — обычный вход, блот — вход с боем.</li>
              <li>Выбрасывание — когда все 15 фишек в своём доме.</li>
            </ul>
          </div>
        )}

        <h3>Главные различия</h3>
        <table className="rules-table">
          <thead>
            <tr><th>Длинные</th><th>Короткие</th></tr>
          </thead>
          <tbody>
            <tr><td>Все 15 начинают на голове</td><td>Расстановка 2–5–3–5</td></tr>
            <tr><td>Бить нельзя</td><td>Одиночные фишки можно бить</td></tr>
            <tr><td>Один соперник закрывает пункт</td><td>Нужно минимум две фишки</td></tr>
            <tr><td>Бара нет</td><td>Есть бар</td></tr>
            <tr><td>Главное оружие — блокирование</td><td>Блокирование + бой</td></tr>
          </tbody>
        </table>

        <div className="modal-actions">
          <button className="btn btn-primary" onClick={onClose}>Понятно</button>
        </div>
      </div>
    </div>
  );
}
